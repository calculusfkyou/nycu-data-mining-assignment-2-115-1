"""Exploratory Data Analysis (EDA) on real SWE-bench Verified candidate runs.

STRICT HYGIENE:
- Computations restricted strictly to Fold 0 training data (1,601 runs: 1,540 normals, 61 deceptive regressions).
- No validation or test data is ever observed during feature analysis.
- Computes Wasserstein distance W, Kolmogorov-Smirnov D_KS, p-values, and medians (IQR).
- Generates publication-ready figures:
  1. Paper/figures/v3/eda.pdf (feature distribution contrasts)
  2. Paper/figures/v3/correlation_heatmap.pdf (structural collinearity)
  3. Paper/generated/v3/v3_stats.tex (LaTeX table)
"""

import json
from pathlib import Path
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy import stats
import seaborn as sns

# Style setup for ACL camera-ready styling
plt.rcParams.update({
    "font.family": "serif",
    "font.size": 10,
    "axes.labelsize": 10,
    "axes.titlesize": 11,
    "xtick.labelsize": 9,
    "ytick.labelsize": 9,
    "legend.fontsize": 9,
    "figure.titlesize": 12,
    "figure.dpi": 300,
})

FEATURES_PATH = Path("Dataset/verified/candidate_features.csv")
SPLITS_PATH = Path("Dataset/verified/splits.json")
FIG_DIR = Path("Paper/figures/v3")
TEX_DIR = Path("Paper/generated/v3")


def format_iqr(series: pd.Series) -> str:
    med = series.median()
    q25 = series.quantile(0.25)
    q75 = series.quantile(0.75)
    if med >= 100:
        return f"{med:.0f} [{q25:.0f}, {q75:.0f}]"
    elif med >= 1:
        return f"{med:.1f} [{q25:.1f}, {q75:.1f}]"
    else:
        return f"{med:.2f} [{q25:.2f}, {q75:.2f}]"


def run_eda():
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    TEX_DIR.mkdir(parents=True, exist_ok=True)

    df_all = pd.read_csv(FEATURES_PATH)
    with open(SPLITS_PATH, "r", encoding="utf-8") as f:
        splits = json.load(f)

    # Restrict strictly to Fold 0 training split
    train_idx = splits["folds"][0]["train_indices"]
    df = df_all.iloc[train_idx].copy().reset_index(drop=True)

    print(f"Loaded Fold 0 Train: {len(df)} runs")
    normals = df[df["label"] == 0]
    anomalies = df[df["label"] == 1]
    print(f"  Normals (Clean): {len(normals)}")
    print(f"  Anomalies (Deceptive Regression): {len(anomalies)} ({len(anomalies)/len(df)*100:.2f}%)")

    feature_cols = [
        ("unverified_edit_ratio", "Unverified Edit Ratio", r"$\text{UER}$"),
        ("cross_module_dispersion", "Cross-Module Dispersion", r"$\text{CMD}$"),
        ("post_test_edit_steps", "Post-Test Edits", r"$\text{PTE}$"),
        ("reproduction_test_ratio", "Test Command Ratio", r"$\text{TCR}$"),
        ("edit_lines_total", "Total Edit Lines (Churn)", r"$\Delta_{\text{lines}}$"),
        ("edit_files_count", "Files Modified", r"$N_{\text{files}}$"),
        ("edit_hunks_count", "Hunks Modified", r"$N_{\text{hunks}}$"),
        ("total_tracebacks", "Terminal Tracebacks", r"$N_{\text{traceback}}$"),
        ("terminal_error_streak", "Max Non-Zero Exit Streak", r"$S_{\text{err}}$"),
        ("repeated_command_count", "Repeated Commands", r"$N_{\text{repeat}}$"),
        ("total_tokens_received", "Tokens Received", r"$T_{\text{recv}}$"),
        ("total_cost_usd", "Inference Cost (USD)", r"$\text{Cost}$"),
    ]

    stats_rows = []
    print("\nFeature Statistical Contrast (Fold 0 Training Set):")
    print("-" * 85)
    print(f"{'Feature':<28} | {'Normal Med [IQR]':<20} | {'Anom Med [IQR]':<20} | {'W':<6} | {'D_KS':<6} | {'p-val'}")
    print("-" * 85)

    for col, name, tex_sym in feature_cols:
        x_norm = normals[col].values
        x_anom = anomalies[col].values

        std_pool = np.std(df[col].values)
        if std_pool == 0:
            std_pool = 1.0

        w_dist = stats.wasserstein_distance(x_norm / std_pool, x_anom / std_pool)
        ks_res = stats.ks_2samp(x_norm, x_anom)

        norm_iqr = format_iqr(normals[col])
        anom_iqr = format_iqr(anomalies[col])

        p_str = f"{ks_res.pvalue:.1e}" if ks_res.pvalue < 0.001 else f"{ks_res.pvalue:.3f}"
        print(f"{name:<28} | {norm_iqr:<20} | {anom_iqr:<20} | {w_dist:.3f} | {ks_res.statistic:.3f} | {p_str}")

        stats_rows.append({
            "col": col,
            "name": name,
            "tex_sym": tex_sym,
            "norm_iqr": norm_iqr,
            "anom_iqr": anom_iqr,
            "w_dist": w_dist,
            "ks_stat": ks_res.statistic,
            "p_val": ks_res.pvalue,
            "p_str": p_str,
        })

    # Generate LaTeX table for paper
    tex_path = TEX_DIR / "v3_stats.tex"
    with open(tex_path, "w", encoding="utf-8") as f:
        f.write("% Auto-generated by EDA/eda_v3.py on Fold-0 Training Data\n")
        f.write(r"\begin{table*}[t]" + "\n")
        f.write(r"\centering" + "\n")
        f.write(r"\small" + "\n")
        f.write(r"\begin{tabular}{lcccc}" + "\n")
        f.write(r"\toprule" + "\n")
        f.write(r"\textbf{Candidate Feature} & \textbf{Clean ($y=0$)} & \textbf{Deceptive ($y=1$)} & \textbf{Wasserstein $W$} & \textbf{KS $D$} \\" + "\n")
        f.write(r"\midrule" + "\n")
        for r in stats_rows:
            p_annot = "$^{***}$" if r["p_val"] < 0.001 else ("$^{**}$" if r["p_val"] < 0.01 else ("$^{*}$" if r["p_val"] < 0.05 else ""))
            f.write(f"{r['name']} & {r['norm_iqr']} & {r['anom_iqr']} & {r['w_dist']:.2f} & {r['ks_stat']:.2f}{p_annot} \\\\\n")
        f.write(r"\bottomrule" + "\n")
        f.write(r"\end{tabular}" + "\n")
        f.write(r"\caption{\textbf{Fold-0 Training Feature Discrepancy.} Comparison between cleanly resolved repairs ($n_0=1,540$) and deceptive regressions ($n_1=61$). Standardized Wasserstein distance $W$ and two-sample Kolmogorov-Smirnov statistic $D$. $^{***}p<0.001$, $^{**}p<0.01$, $^{*}p<0.05$.}" + "\n")
        f.write(r"\label{tab:eda_stats}" + "\n")
        f.write(r"\end{table*}" + "\n")
    print(f"\nSaved LaTeX table to {tex_path}")

    # Generate 3-panel distribution figure (eda.pdf)
    fig, axes = plt.subplots(1, 3, figsize=(10, 2.3))

    # Panel A: Unverified Edit Ratio
    sns.kdeplot(data=normals["unverified_edit_ratio"], ax=axes[0], label="Clean (y=0)", fill=True, color="#2b5c8f", alpha=0.35, common_norm=False)
    sns.kdeplot(data=anomalies["unverified_edit_ratio"], ax=axes[0], label="Regression (y=1)", fill=True, color="#d95f02", alpha=0.35, common_norm=False)
    axes[0].set_title("(a) Unverified Edit Ratio (UER)")
    axes[0].set_xlabel("Ratio of Edited Files Untested")
    axes[0].set_ylabel("Density")
    axes[0].legend(loc="upper right", frameon=True)
    axes[0].grid(True, linestyle="--", alpha=0.4)

    # Panel B: Cross-Module Dispersion
    disp_norm = normals["cross_module_dispersion"].value_counts(normalize=True).sort_index()
    disp_anom = anomalies["cross_module_dispersion"].value_counts(normalize=True).sort_index()
    all_dirs = sorted(list(set(disp_norm.index).union(set(disp_anom.index))))
    all_dirs = [d for d in all_dirs if d <= 6]
    width = 0.38
    x_pos = np.arange(len(all_dirs))
    axes[1].bar(x_pos - width/2, [disp_norm.get(d, 0) for d in all_dirs], width=width, label="Clean (y=0)", color="#2b5c8f", alpha=0.85)
    axes[1].bar(x_pos + width/2, [disp_anom.get(d, 0) for d in all_dirs], width=width, label="Regression (y=1)", color="#d95f02", alpha=0.85)
    axes[1].set_title("(b) Cross-Module Dispersion (CMD)")
    axes[1].set_xlabel("Distinct Top-Level Dirs Touched")
    axes[1].set_ylabel("Proportion")
    axes[1].set_xticks(x_pos)
    axes[1].set_xticklabels([str(d) for d in all_dirs])
    axes[1].legend(loc="upper right", frameon=True)
    axes[1].grid(True, linestyle="--", alpha=0.4, axis="y")

    # Panel C: Total Edit Lines (log scale)
    sns.boxplot(data=df, x="label", y="edit_lines_total", hue="label", ax=axes[2], palette=["#2b5c8f", "#d95f02"], showfliers=False, legend=False)
    axes[2].set_yscale("log")
    axes[2].set_title(r"(c) Patch Churn ($\Delta_{\text{lines}}$)")
    axes[2].set_xlabel("Ground Truth Label")
    axes[2].set_ylabel("Total Lines Modified (log)")
    axes[2].set_xticks([0, 1])
    axes[2].set_xticklabels(["Clean (y=0)", "Regression (y=1)"])
    axes[2].grid(True, linestyle="--", alpha=0.4, axis="y")

    plt.tight_layout()
    eda_fig_path = FIG_DIR / "eda.pdf"
    plt.savefig(eda_fig_path, bbox_inches="tight")
    plt.savefig(FIG_DIR / "eda.png", bbox_inches="tight", dpi=300)
    plt.close()
    print(f"Saved EDA distribution figure to {eda_fig_path}")

    # Generate Feature Correlation Heatmap (correlation_heatmap.pdf)
    heatmap_cols = [
        "unverified_edit_ratio", "cross_module_dispersion", "post_test_edit_steps",
        "reproduction_test_ratio", "edit_lines_total", "edit_files_count",
        "total_tracebacks", "terminal_error_streak", "repeated_command_count"
    ]
    corr = df[heatmap_cols].corr(method="spearman")
    fig, ax = plt.subplots(figsize=(6.5, 5.2))
    cmap = sns.diverging_palette(240, 10, as_cmap=True)
    sns.heatmap(corr, annot=True, fmt=".2f", cmap=cmap, vmin=-0.6, vmax=0.8,
                square=True, linewidths=0.5, cbar_kws={"shrink": 0.8}, ax=ax)
    ax.set_title("Spearman Rank Correlation Across Structural Features")
    plt.tight_layout()
    corr_fig_path = FIG_DIR / "correlation_heatmap.pdf"
    plt.savefig(corr_fig_path, bbox_inches="tight")
    plt.savefig(FIG_DIR / "correlation_heatmap.png", bbox_inches="tight", dpi=300)
    plt.close()
    print(f"Saved correlation heatmap to {corr_fig_path}")


if __name__ == "__main__":
    run_eda()
